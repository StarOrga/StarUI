#!/usr/bin/env node
/**
 * Generate the complete desktop icon family from the SVG sources.
 *
 * StarUI is the master of these assets: consumers (SC-App and any other
 * StarUI-based app) re-vendor the icon, tray and brand rasters from here
 * instead of generating their own copies.
 *
 * Two independent rendering paths, because a taskbar icon and a notification-area
 * icon have different constraints:
 *
 *  1. APP / TASKBAR path — source `assets/brand/app-icon-taskbar.svg`.
 *     The full brain-nebula artwork (cloud layers, accretion disk, brain core).
 *     Rendered at 16/24/32/48/64/128/256/512 plus the multi-resolution .ico files.
 *
 *  2. TRAY path — a dedicated small-size mark generated by this script.
 *     The full artwork does not survive a 16px render: Gaussian blur filters turn
 *     into mud, and the dark `#0d2635` disc plus a ~2px core is invisible on a dark
 *     Windows taskbar. The tray mark therefore drops every filter, fills the canvas,
 *     and carries a bright coloured rim so the silhouette reads on BOTH a dark and a
 *     light taskbar. Rendered at every size Windows asks for (16/20/24/32), so Qt
 *     never has to rescale.
 *
 * Usage: node scripts/gen-app-icons.js  (npm run gen:icons)
 *
 * Outputs:
 *   assets/brand/app-icon.png                   512
 *   assets/brand/app-icon.ico                   16..256 multi-res
 *   assets/icons/app-icon-{16,24,32,48,64,128,256,512}.png
 *   assets/icons/app-icon.ico                   16..256 multi-res
 *   assets/tray/tray-<state>.svg                32x32 source
 *   assets/tray/tray-<state>.png                32 (canonical)
 *   assets/tray/tray-<state>-{16,20,24}.png
 *
 * Re-run this script after ANY change to app-icon-taskbar.svg or to TRAY_STATES,
 * commit the regenerated files, and release a StarUI tag for the consumers.
 */
'use strict';

const fs = require('fs');
const path = require('path');

// Loaded on first use, so the constants exported below stay requirable where
// sharp's platform binary is missing (it is a devDependency of StarUI only).
let sharpModule = null;
function sharp(...args) {
  if (!sharpModule) sharpModule = require('sharp');
  return sharpModule(...args);
}

const REPO = path.join(__dirname, '..');
const RES = path.join(REPO, 'assets', 'brand');
const ICONS_DIR = path.join(REPO, 'assets', 'icons');
const TRAY_DIR = path.join(REPO, 'assets', 'tray');

const APP_SVG = path.join(RES, 'app-icon-taskbar.svg');

/** Sizes shipped as standalone app-icon PNGs. */
const APP_PNG_SIZES = [16, 24, 32, 48, 64, 128, 256, 512];
/** Sizes embedded in every .ico. Matches what Explorer/taskbar/alt-tab request. */
const ICO_SIZES = [16, 24, 32, 48, 64, 128, 256];
/** Sizes the Windows notification area requests at 100/125/150/200% scaling. */
const TRAY_SIZES = [16, 20, 24, 32];
/** The tray PNG written without a size suffix (consumed by the Electron fallback). */
const TRAY_CANONICAL = 32;

// ---------------------------------------------------------------------------
// Tray mark
// ---------------------------------------------------------------------------

/**
 * Palette per tray state. Every state must stay tellable apart at 16px, so the
 * differences are structural (hue / rim weight / core size), never a subtle tint:
 *
 *   cyan   → normal operation      (default, default-glow, active)
 *   slate  → nothing running       (idle)
 *   gold   → attention wanted      (notification, notification-glow)
 *   red    → something failed      (error)
 *
 * `accent` paints the gold accretion particle — only `active` carries it, which is
 * what separates "running" from the otherwise similar bright-cyan glow state.
 */
const TRAY_STATES = {
  'default': {
    ring: '#52c1e6', disk: '#7dd5f0', core: '#a0dcf0',
    ringW: 1.8, ringO: 0.85, diskO: 0.55, haloO: 0.55, coreR: 3.4, accent: null,
  },
  'default-glow': {
    ring: '#7dd5f0', disk: '#a0dcf0', core: '#d9f3fc',
    ringW: 2.2, ringO: 1.0, diskO: 0.7, haloO: 0.95, coreR: 4.2, accent: null,
  },
  'active': {
    ring: '#52c1e6', disk: '#7dd5f0', core: '#c9edfa',
    ringW: 2.0, ringO: 0.95, diskO: 0.75, haloO: 0.8, coreR: 3.9, accent: '#c8a84b',
  },
  'idle': {
    ring: '#7fa3b4', disk: '#8fb0bf', core: '#b8d2de',
    ringW: 1.7, ringO: 0.88, diskO: 0.4, haloO: 0.22, coreR: 3.0, accent: null,
  },
  'notification': {
    ring: '#c8a84b', disk: '#e0c268', core: '#f2dc9a',
    ringW: 1.8, ringO: 0.92, diskO: 0.55, haloO: 0.55, coreR: 3.4, accent: null,
  },
  'notification-glow': {
    ring: '#e8c85f', disk: '#f2dc9a', core: '#fff4d2',
    ringW: 2.2, ringO: 1.0, diskO: 0.7, haloO: 0.95, coreR: 4.2, accent: null,
  },
  'error': {
    ring: '#e05a5a', disk: '#f08a8a', core: '#ffdada',
    ringW: 2.0, ringO: 1.0, diskO: 0.55, haloO: 0.6, coreR: 3.4, accent: null,
  },
};

/** Dark disc of the brand mark. Gives the silhouette on a LIGHT taskbar. */
const DISC = '#0d2635';

function trayMarkSvg(state, s) {
  // Rim radius is derived so the stroke lands fully inside the 32-unit canvas.
  const rimR = (16 - s.ringW / 2 - 0.35).toFixed(2);
  const haloMid = (s.haloO * 0.5).toFixed(3);
  const diskInnerO = (s.diskO * 0.6).toFixed(3);
  const particle = s.accent
    ? `\n<circle cx="24.4" cy="10.2" r="1.6" fill="${s.accent}" opacity=".95"/>`
    : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="32" height="32">
<!-- GENERATED by scripts/gen-app-icons.js, do not edit by hand.
     Small-size tray mark for state "${state}": dark disc, coloured accretion ring,
     glowing core. No blur filters and no margin; both are unreadable at 16px. -->
<defs>
  <radialGradient id="halo"><stop offset="0%" stop-color="${s.core}" stop-opacity="${s.haloO}"/><stop offset="40%" stop-color="${s.disk}" stop-opacity="${haloMid}"/><stop offset="100%" stop-color="${s.disk}" stop-opacity="0"/></radialGradient>
  <radialGradient id="core"><stop offset="0%" stop-color="#ffffff" stop-opacity=".92"/><stop offset="38%" stop-color="${s.core}"/><stop offset="100%" stop-color="${s.disk}"/></radialGradient>
</defs>
<!-- Dark disc: carries the silhouette on a light taskbar -->
<circle cx="16" cy="16" r="15.05" fill="${DISC}" fill-opacity=".97"/>
<!-- Bright rim: carries the silhouette on a dark taskbar -->
<circle cx="16" cy="16" r="${rimR}" fill="none" stroke="${s.ring}" stroke-width="${s.ringW}" stroke-opacity="${s.ringO}"/>
<!-- Accretion disk -->
<g transform="rotate(-22 16 16)">
  <ellipse cx="16" cy="16" rx="10.4" ry="3.6" fill="none" stroke="${s.disk}" stroke-width="1.15" stroke-opacity="${s.diskO}"/>
  <ellipse cx="16" cy="16" rx="7.0" ry="2.4" fill="none" stroke="${s.disk}" stroke-width=".8" stroke-opacity="${diskInnerO}"/>
</g>${particle}
<!-- Glowing core -->
<circle cx="16" cy="16" r="8.4" fill="url(#halo)"/>
<circle cx="16" cy="16" r="${s.coreR}" fill="url(#core)"/>
</svg>
`;
}

// ---------------------------------------------------------------------------
// ICO writer
// ---------------------------------------------------------------------------

/**
 * Encode one icon image as a 32bpp BITMAPINFOHEADER DIB (bottom-up BGRA plus a
 * padded 1bpp AND mask). Windows needs the DIB form for the small sizes; only the
 * 256px entry is stored as PNG, which is the same layout every ICO tool emits.
 */
function encodeDib(rgba, size) {
  const rowMask = Math.ceil(size / 32) * 4; // AND mask rows are DWORD-aligned
  const xor = Buffer.alloc(size * size * 4);
  const and = Buffer.alloc(rowMask * size);
  for (let y = 0; y < size; y++) {
    const srcY = size - 1 - y; // DIBs are stored bottom-up
    for (let x = 0; x < size; x++) {
      const s = (srcY * size + x) * 4;
      const d = (y * size + x) * 4;
      xor[d] = rgba[s + 2];
      xor[d + 1] = rgba[s + 1];
      xor[d + 2] = rgba[s];
      xor[d + 3] = rgba[s + 3];
      // Fully transparent pixels are also flagged in the legacy AND mask so
      // pre-alpha consumers do not paint a black box.
      if (rgba[s + 3] === 0) {
        and[y * rowMask + (x >> 3)] |= 0x80 >> (x & 7);
      }
    }
  }
  const header = Buffer.alloc(40);
  header.writeUInt32LE(40, 0);
  header.writeInt32LE(size, 4);
  header.writeInt32LE(size * 2, 8); // XOR + AND stacked
  header.writeUInt16LE(1, 12);
  header.writeUInt16LE(32, 14);
  header.writeUInt32LE(0, 16); // BI_RGB
  header.writeUInt32LE(xor.length + and.length, 20);
  return Buffer.concat([header, xor, and]);
}

async function buildIco(svgPath, sizes) {
  const images = [];
  for (const size of sizes) {
    const png = await renderPng(svgPath, size);
    if (size >= 256) {
      images.push({ size, data: png });
      continue;
    }
    const { data } = await sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    images.push({ size, data: encodeDib(data, size) });
  }
  const dir = Buffer.alloc(6 + images.length * 16);
  dir.writeUInt16LE(0, 0);
  dir.writeUInt16LE(1, 2); // 1 = icon
  dir.writeUInt16LE(images.length, 4);
  let offset = dir.length;
  images.forEach((img, i) => {
    const o = 6 + i * 16;
    dir[o] = img.size >= 256 ? 0 : img.size; // 0 means 256
    dir[o + 1] = img.size >= 256 ? 0 : img.size;
    dir[o + 2] = 0;
    dir[o + 3] = 0;
    dir.writeUInt16LE(1, o + 4);
    dir.writeUInt16LE(32, o + 6);
    dir.writeUInt32LE(img.data.length, o + 8);
    dir.writeUInt32LE(offset, o + 12);
    offset += img.data.length;
  });
  return Buffer.concat([dir, ...images.map((i) => i.data)]);
}

// ---------------------------------------------------------------------------
// Rendering
// ---------------------------------------------------------------------------

/**
 * Rasterise an SVG at an exact pixel size.
 *
 * Rendering the vector directly at the target size (rather than downscaling one
 * big raster) is what keeps 16px legible: strokes get hinted against the real
 * pixel grid instead of being averaged away.
 */
function renderPng(svgPathOrBuffer, size) {
  const input = Buffer.isBuffer(svgPathOrBuffer) ? svgPathOrBuffer : fs.readFileSync(svgPathOrBuffer);
  return sharp(input, { density: 1400 })
    .resize(size, size, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png({ compressionLevel: 9 })
    .toBuffer();
}

function write(target, buffer) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, buffer);
  console.log(`  ${path.relative(REPO, target).replace(/\\/g, '/')}  (${buffer.length} bytes)`);
}

async function generateAppIcons() {
  console.log('app / taskbar icons  <- assets/brand/app-icon-taskbar.svg');
  for (const size of APP_PNG_SIZES) {
    write(path.join(ICONS_DIR, `app-icon-${size}.png`), await renderPng(APP_SVG, size));
  }
  write(path.join(RES, 'app-icon.png'), await renderPng(APP_SVG, 512));

  const ico = await buildIco(APP_SVG, ICO_SIZES);
  write(path.join(RES, 'app-icon.ico'), ico);
  write(path.join(ICONS_DIR, 'app-icon.ico'), ico);
}

async function generateTrayIcons() {
  console.log('tray icons  <- generated small-size mark');
  for (const [state, palette] of Object.entries(TRAY_STATES)) {
    const svg = trayMarkSvg(state, palette);
    write(path.join(TRAY_DIR, `tray-${state}.svg`), Buffer.from(svg, 'utf8'));
    const buf = Buffer.from(svg, 'utf8');
    for (const size of TRAY_SIZES) {
      const name = size === TRAY_CANONICAL ? `tray-${state}.png` : `tray-${state}-${size}.png`;
      write(path.join(TRAY_DIR, name), await renderPng(buf, size));
    }
  }
}

async function main() {
  await generateAppIcons();
  await generateTrayIcons();
  console.log('done.');
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}

module.exports = { TRAY_STATES, TRAY_SIZES, TRAY_CANONICAL, APP_PNG_SIZES, ICO_SIZES, trayMarkSvg };
